// Suggests path units for a subject and prints a ready-to-edit migration. Read-only: it changes nothing.
// Run: npm run path:suggest -- <subject-id> [target]
//
// It walks the subject's topics in syllabus order and joins neighbours until each unit holds about
// `target` distinct published questions (default 30), then folds a short tail into the unit before it.
// The names are only a starting point: rename them, add a theme, and review the groups before applying.
import postgres from "postgres";

const [subject, targetArg] = process.argv.slice(2);
const target = Number(targetArg ?? 30);
if (!subject) {
  console.error("Usage: npm run path:suggest -- <subject-id> [target]");
  process.exit(1);
}

const sql = postgres(process.env.SUPABASE_DB_URL, { max: 1, prepare: false, onnotice: () => {} });
const MIN = 20;

try {
  const [existing] = await sql`select count(*)::int as n from public.path_units where subject_id = ${subject}`;
  if (existing.n > 0) {
    console.error(`-- ${subject} already has ${existing.n} units. New topics join on their own; regroup with an UPDATE instead.`);
    process.exit(1);
  }
  const topics = await sql`
    select t.slug, t.name, count(distinct q.content_hash)::int as n
    from public.topics t
    left join public.questions q on q.topic_id = t.id and q.status = 'published'
    where t.subject_id = ${subject} and t.active
    group by t.id order by t.sort_order, t.name`;
  if (topics.length === 0) {
    console.error(`No active topics for "${subject}".`);
    process.exit(1);
  }

  const groups = [];
  let current = [];
  let count = 0;
  for (const t of topics) {
    current.push(t);
    count += t.n;
    if (count >= target) {
      groups.push(current);
      current = [];
      count = 0;
    }
  }
  if (current.length) {
    const tail = current.reduce((sum, t) => sum + t.n, 0);
    if (groups.length && tail < MIN) groups[groups.length - 1].push(...current);
    else groups.push(current);
  }

  const total = (g) => g.reduce((sum, t) => sum + t.n, 0);
  const slugOf = (g) => g[0].slug.slice(0, 48);
  const nameOf = (g) => {
    const names = g.map((t) => t.name);
    const joined = names.length === 1 ? names[0] : `${names.slice(0, -1).join(", ")} and ${names.at(-1)}`;
    return joined.length <= 70 ? joined : `${names[0]} and more`;
  };
  const q = (s) => `'${s.replace(/'/g, "''")}'`;

  console.log(`-- Path units for ${subject}: ${topics.length} topics in ${groups.length} units (${topics.reduce((s, t) => s + t.n, 0)} questions).`);
  console.log(`-- Generated by npm run path:suggest. Rename the units, set a theme for each, then review the groups.\n`);
  console.log(`with u(slug, name, sort_order, theme, theme_order) as (values`);
  console.log(
    groups
      .map((g, i) => `  (${q(slugOf(g))}, ${q(nameOf(g))}, ${(i + 1) * 10}, null, null)${i < groups.length - 1 ? "," : ""}  -- ${total(g)} questions`)
      .join("\n"),
  );
  console.log(`)\ninsert into public.path_units (subject_id, slug, name, sort_order, theme, theme_order)\nselect ${q(subject)}, slug, name, sort_order, theme, theme_order from u;\n`);
  console.log(`with m(unit_slug, topic_slug) as (values`);
  console.log(groups.flatMap((g) => g.map((t) => `  (${q(slugOf(g))}, ${q(t.slug)})`)).join(",\n"));
  console.log(`)
insert into public.path_unit_topics (unit_id, topic_id)
select pu.id, t.id
from m
join public.path_units pu on pu.subject_id = ${q(subject)} and pu.slug = m.unit_slug
join public.topics t on t.subject_id = ${q(subject)} and t.slug = m.topic_slug;
`);
  const thin = groups.filter((g) => total(g) < MIN);
  if (thin.length) console.log(`-- Heads up: ${thin.length} unit(s) hold fewer than ${MIN} questions. They work, but repeat sooner.`);
} finally {
  await sql.end();
}
